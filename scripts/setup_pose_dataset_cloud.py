#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Setup script for cloud GPU: create image symlinks for the True-Quad Pose dataset.

Usage:
  # 1. Extract the package on the cloud GPU
  # 2. Make sure CCPD2019, CCPD2020, CRPD datasets are available
  # 3. Run this script to create image symlinks

  python3 setup_pose_dataset_cloud.py --dataset-dir . \
    --ccpd2019-dir /path/to/CCPD2019 \
    --ccpd2020-dir /path/to/CCPD2020/ccpd_green \
    --crpd-dir /path/to/CRPD_all

Environment variables can replace the flags:
  CCPD2019_DIR=/path  CCPD2020_DIR=/path  CRPD_DIR=/path

The script reads image_sources.tsv (generated by build_true_quad_pose_dataset.py)
which maps each new filename to its original absolute path. The original paths
are then patched to point to the local CCPD/CRPD directories on the cloud.
"""

import argparse
import os
import sys
from pathlib import Path


def resolve_source_path(orig_abs_path: str, src_root: Path, src_type: str) -> str:
    """
    Given an original absolute path (from the local machine) and a cloud-side
    source root, compute the corresponding cloud-side path.

    src_type: 'ccpd2019', 'ccpd2020', 'crpd'
    """
    orig_path = Path(orig_abs_path)
    fname = orig_path.name

    if src_type == "ccpd2019":
        # Original: /home/wzzz/LPRNet/datasets/CCPD2019/ccpd_*/xxx.jpg
        # Cloud:   {ccpd2019_dir}/ccpd_*/xxx.jpg
        # The subdirectory is the parent of the filename in the original path
        subdir = orig_path.parent.name  # e.g., "ccpd_base", "ccpd_tilt"
        candidate = src_root / subdir / fname
        if candidate.exists():
            return str(candidate)
        # Fallback: search all ccpd_* subdirs
        for sd in sorted(os.listdir(src_root)):
            if sd.startswith("ccpd_") and not sd.endswith(".cache"):
                c = src_root / sd / fname
                if c.exists():
                    return str(c)

    elif src_type == "ccpd2020":
        # Original: /home/wzzz/LPRNet/datasets/CCPD2020/ccpd_green/{split}/xxx.jpg
        # Cloud:   {ccpd2020_dir}/{split}/xxx.jpg
        for split in ["train", "val", "test"]:
            candidate = src_root / split / fname
            if candidate.exists():
                return str(candidate)

    elif src_type == "crpd":
        # Original: /home/wzzz/LPRNet/datasets/CRPD_all/CRPD_{subset}/{split}/images/xxx.jpg
        # Cloud:   {crpd_dir}/CRPD_{subset}/{split}/images/xxx.jpg
        for subset in ["single", "double", "multi"]:
            for split in ["train", "val", "test"]:
                candidate = src_root / f"CRPD_{subset}" / split / "images" / fname
                if candidate.exists():
                    return str(candidate)

    return None


def infer_source_type(orig_abs_path: str) -> str:
    """Infer the source dataset type from the original absolute path."""
    p = orig_abs_path.replace("\\", "/")
    if "/CCPD2019/" in p or "/ccpd_base/" in p or "/ccpd_tilt/" in p:
        return "ccpd2019"
    if "/CCPD2020/" in p or "/ccpd_green/" in p:
        return "ccpd2020"
    if "/CRPD_all/" in p or "/CRPD_single/" in p or "/CRPD_double/" in p or "/CRPD_multi/" in p:
        return "crpd"
    # Fallback: check the tag prefix in the new filename
    return None


def main():
    parser = argparse.ArgumentParser(
        description="Setup True-Quad Pose dataset on cloud GPU: create image symlinks."
    )
    parser.add_argument("--dataset-dir", type=str, required=True,
                        help="Path to plate_true_quad_pose dataset directory")
    parser.add_argument("--ccpd2019-dir", type=str, default=None,
                        help="Path to CCPD2019 dataset root")
    parser.add_argument("--ccpd2020-dir", type=str, default=None,
                        help="Path to CCPD2020/ccpd_green directory")
    parser.add_argument("--crpd-dir", type=str, default=None,
                        help="Path to CRPD_all directory")
    args = parser.parse_args()

    dataset_dir = Path(args.dataset_dir)
    if not dataset_dir.exists():
        print(f"[ERROR] Dataset dir not found: {dataset_dir}")
        return 1

    # Check for image_sources.tsv
    tsv_path = dataset_dir / "image_sources.tsv"
    if not tsv_path.exists():
        print(f"[ERROR] image_sources.tsv not found at {tsv_path}")
        print("  This file is required. It maps new filenames to original source paths.")
        print("  Re-run build_true_quad_pose_dataset.py to regenerate it.")
        return 1

    # Detect source directories
    source_dirs = {
        "ccpd2019": args.ccpd2019_dir or os.environ.get("CCPD2019_DIR", ""),
        "ccpd2020": args.ccpd2020_dir or os.environ.get("CCPD2020_DIR", ""),
        "crpd": args.crpd_dir or os.environ.get("CRPD_DIR", ""),
    }

    # Check which exist
    for key, path in list(source_dirs.items()):
        resolved = Path(path)
        if not path or not resolved.exists():
            print(f"[WARN] {key} dir not found: {path or 'not set'}")
            print(f"       Provide via --{key}-dir or ${key.upper()}_DIR")
        else:
            print(f"[OK] {key} -> {resolved.resolve()}")

    # Read image_sources.tsv
    print(f"\nReading image_sources.tsv...")
    entries = []
    with open(tsv_path, encoding="utf-8") as f:
        header = f.readline()  # skip header
        for line in f:
            line = line.strip()
            if not line:
                continue
            parts = line.split("\t", 1)
            if len(parts) != 2:
                continue
            new_rel_path, orig_abs_path = parts
            entries.append((new_rel_path, orig_abs_path))

    print(f"  {len(entries)} entries loaded")

    # Create symlinks
    linked = 0
    skipped = 0
    errors = 0
    unresolved = 0

    images_dir = dataset_dir / "images"

    for idx, (new_rel_path, orig_abs_path) in enumerate(entries):
        dst_path = images_dir / new_rel_path

        if dst_path.exists() or dst_path.is_symlink():
            skipped += 1
            continue

        # Determine source type from original path
        src_type = infer_source_type(orig_abs_path)
        if src_type is None or not source_dirs.get(src_type):
            unresolved += 1
            dst_path.parent.mkdir(parents=True, exist_ok=True)
            # As last resort, try using the original path directly
            if os.path.exists(orig_abs_path):
                rel_src = os.path.relpath(orig_abs_path, dst_path.parent)
                os.symlink(rel_src, dst_path)
                linked += 1
            else:
                errors += 1
            continue

        # Resolve cloud-side source path
        src_root = Path(source_dirs[src_type])
        src_path = resolve_source_path(orig_abs_path, src_root, src_type)

        if src_path is None:
            fname = Path(orig_abs_path).name
            errors += 1
            if errors <= 10:
                print(f"    [ERR] Not found: {new_rel_path} ({fname})")
            continue

        dst_path.parent.mkdir(parents=True, exist_ok=True)
        rel_src = os.path.relpath(src_path, dst_path.parent)
        os.symlink(rel_src, dst_path)
        linked += 1

        if linked % 5000 == 0:
            print(f"    ... {linked} linked")

    print(f"\n{'=' * 60}")
    print(f"Symlink setup complete:")
    print(f"  Linked:    {linked}")
    print(f"  Skipped:   {skipped} (already exist)")
    print(f"  Errors:    {errors} (source not found)")
    print(f"  Unresolved:{unresolved} (unknown source type)")
    print(f"{'=' * 60}")

    if errors > 0 or unresolved > 0:
        print(f"\nCheck the missing entries in image_sources.tsv and verify")
        print(f"that the CCPD2019, CCPD2020, and CRPD directories are correct.")
        return 1

    # Update dataset.yaml path to absolute
    yaml_path = dataset_dir / "dataset.yaml"
    if yaml_path.exists():
        abs_dataset_dir = dataset_dir.resolve()
        content = yaml_path.read_text()
        import re
        content = re.sub(r'^path: .*', f'path: {abs_dataset_dir}', content, flags=re.MULTILINE)
        yaml_path.write_text(content)
        print(f"\n[OK] Updated dataset.yaml path to: {abs_dataset_dir}")

    print(f"\nReady to train! Run:")
    print(f"  yolo pose train model=yolov8n-pose.pt \\")
    print(f"    data={dataset_dir}/dataset.yaml \\")
    print(f"    imgsz=640 epochs=100 batch=64 workers=8 \\")
    print(f"    kpt_shape=[4,3] fliplr=0.0 cache=ram")

    return 0


if __name__ == "__main__":
    sys.exit(main())
